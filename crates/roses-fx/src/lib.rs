use types::{EffectUpdate, EffectWorld};

/// A hand-ported effect program, driven like
/// `roses_ee::bmodule::AttackEffect`: the first [`update`](Self::update) is
/// the launch call (`entry(data, param)`), each later one `entry(data,
/// -1)`; return 8 ends it.
pub trait EffectPort: Send {
    /// The launch or the next update.
    fn update(&mut self, world: &dyn EffectWorld) -> EffectUpdate;
    /// Calls made (the launch is call 0).
    fn calls(&self) -> usize;
    /// Returned 8.
    fn finished(&self) -> bool;
    /// The program's rand state (newlib's u64, as the interpreter's
    /// `AttackEffect::rand_state`).
    fn rand_state(&mut self) -> u64;
    fn set_rand_state(&mut self, state: u64);
    /// `role`'s motion after the last call: (motion obj+0x1E0, time
    /// obj+0x19C, blend updates obj+0x1FB), for programs that change it.
    fn object_motion(&self, _role: usize) -> Option<(u8, f32, u8)> {
        None
    }
    /// The port's memory picture (debugging: compared with the oracle's).
    fn bus(&mut self) -> Option<&mut dyn bus::Bus> {
        None
    }
}
